import { describe, expect, it } from 'vitest';
import { readFileSync } from 'node:fs';
import { resolve } from 'node:path';

// Guards the Scripture font stack in fonts.css. The failure modes are SILENT and
// platform-dependent, and there are two of them.
//
// A family declared only at weight 400 / style normal renders a bold or italic run by distorting
// the regular face — a smeared fake bold and a slanted roman rather than the family's real italic
// letterforms. Nothing errors, and on a machine where the font is also installed locally nothing
// even looks wrong, because the installed family supplies the real faces.
//
// A family whose matching face FAILS to load is worse: it does not fall back to another face of
// the same family, or to an installed copy of it, but drops out of the family altogether and
// lands on whatever comes next in the stack. That is why every face here has to resolve to a real
// font file, and why the families Paratext installs name the installed copy inside their own
// `src` — a `local()` there is the only thing that still resolves with no network.
//
// The stylesheet's font-face region is generated by fetching the commented-out `@import` URL at the
// top of fonts.css and pasting Google's response in whole, so that URL is where a family gains a
// weight or style: its `ital,wght` axes must name every combination the family is used at, and
// every face the response emits has to be pasted. Pasting only part of a style leaves exactly the
// characters in the dropped `unicode-range` subsets falling out of the family.

const fontsCssPath = resolve(__dirname, 'fonts.css');
const repoRoot = resolve(__dirname, '../../..');

/** One `@font-face` rule's descriptors, with whitespace and quoting normalized. */
type FontFace = {
  family: string;
  style: string;
  /** The `font-weight` descriptor verbatim — a single value (`400`) or a range (`100 900`). */
  weight: string;
  src: string;
  unicodeRange: string;
};

/** A weight/style pair the stack must be able to render with a real face. */
type RequiredFace = { weight: number; style: string };

/**
 * Faces each downloaded Scripture-stack family must declare. Every family here is named in
 * `--scripture-font-stack`, and every entry must be backed by a real font file rather than left to
 * the browser to synthesize from the regular face.
 *
 * Bold italic is absent for Cardo, and italic entirely for Noto Sans Syriac, because the upstream
 * families ship no such face.
 */
const REQUIRED_FACES: Readonly<{ [family: string]: readonly RequiredFace[] }> = {
  'Charis SIL': [
    { weight: 400, style: 'normal' },
    { weight: 400, style: 'italic' },
    { weight: 700, style: 'normal' },
    { weight: 700, style: 'italic' },
  ],
  'Gentium Plus': [
    { weight: 400, style: 'normal' },
    { weight: 400, style: 'italic' },
    { weight: 700, style: 'normal' },
    { weight: 700, style: 'italic' },
  ],
  Cardo: [
    { weight: 400, style: 'normal' },
    { weight: 400, style: 'italic' },
    { weight: 700, style: 'normal' },
  ],
  'Noto Sans Syriac': [
    { weight: 400, style: 'normal' },
    { weight: 700, style: 'normal' },
  ],
};

/**
 * The families whose faces name an installed copy ahead of the download, mapped to the PostScript
 * name stem those copies use. They are the stack's only offline path: with no network every face
 * with nothing but a `url()` fails, and a family whose faces all fail drops out rather than falling
 * back to an installed copy of the same name.
 */
const INSTALLED_FIRST_FAMILIES: Readonly<{ [family: string]: string }> = {
  'Charis SIL': 'CharisSIL',
  'Gentium Plus': 'GentiumPlus',
};

/**
 * The `local()` sources a face must name, by weight and style — the table the region's own comment
 * spells out, so a paste that was re-pasted and half-edited fails here rather than at a
 * translator's desk with no network. Full font name first, then the PostScript name: which one a
 * platform matches varies, and naming both covers either.
 */
const LOCAL_SOURCE_NAMES: Readonly<{ [face: string]: readonly [string, string] }> = {
  '400/normal': ['{family}', '{stem}-Regular'],
  '700/normal': ['{family} Bold', '{stem}-Bold'],
  '400/italic': ['{family} Italic', '{stem}-Italic'],
  '700/italic': ['{family} Bold Italic', '{stem}-BoldItalic'],
};

/**
 * Families in the stack that are deliberately NOT in {@link REQUIRED_FACES}, each with the reason it
 * is safe to leave uncovered. This is what makes the coverage check two-directional: adding a
 * family to the stack with only its regular face pasted in fails the suite until someone either
 * declares the rest of its faces or writes down why it does not need them.
 */
const UNGUARDED_STACK_FAMILIES: Readonly<{ [family: string]: string }> = {
  'Google Sans': [
    'The application chrome font, in the Scripture stack only as a last resort ahead of the generic',
    '`serif`. It is declared at a single weight and style, so a bold or italic request against it is',
    'synthesized rather than dropped — there is no competing face to fail. If it ever gains a second',
    'face, it needs full coverage like the rest.',
  ].join(' '),
};


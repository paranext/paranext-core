// Pure helpers for the "Library dist current" check and its GitHub workflows. Standard library
// only and erasable TypeScript only, so plain `node` can load this file before `npm ci`.

export const LIBRARY_DIRS = ['lib/platform-bible-react', 'lib/platform-bible-utils'] as const;

/** Commit status context that branch protection requires. */
export const STATUS_CONTEXT = 'Library dist current';

/**
 * Description the check workflow writes before it knows the outcome. The workflow's `printf` lines
 * must use this exact text.
 */
export const PLACEHOLDER_DESCRIPTION = 'Checking';

/** `gh pr list --json files` returns at most this many files per pull request. */
const GH_FILE_LIST_LIMIT = 100;

const FULL_SHA_PATTERN = /^[0-9a-f]{40}$/;

// Paths are ASCII and machine-generated by git, so native String methods are correct here.
export function isLibraryPath(filePath: string): boolean {
  return (
    filePath === 'package-lock.json' ||
    filePath === 'package.json' ||
    LIBRARY_DIRS.some((dir) => filePath.startsWith(`${dir}/`))
  );
}

export function hasLibraryChanges(filePaths: readonly string[]): boolean {
  return filePaths.some(isLibraryPath);
}

export type OpenPullRequest = { number: number; headRefOid: string; files: { path: string }[] };

/**
 * Keeps the pull requests that touch a library. A pull request whose file list hit the `gh` limit
 * may have library files beyond it, so it is kept.
 */
export function selectLibraryPullRequests(
  pullRequests: readonly OpenPullRequest[],
): OpenPullRequest[] {
  return pullRequests.filter(
    (pullRequest) =>
      pullRequest.files.length >= GH_FILE_LIST_LIMIT ||
      hasLibraryChanges(pullRequest.files.map((file) => file.path)),
  );
}

export type CheckTarget = { pr?: number; sha: string; description: string };

/**
 * Parses a check target from JSON. The JSON comes from an artifact a fork pull request's run can
 * write, so it is untrusted: anything that is not exactly the expected shape yields `undefined`.
 */
export function parseTarget(json: string): CheckTarget | undefined {
  let value: unknown;
  try {
    value = JSON.parse(json);
  } catch {
    return undefined;
  }
  if (!value || typeof value !== 'object' || Array.isArray(value)) return undefined;
  const pr: unknown = Reflect.get(value, 'pr');
  const sha: unknown = Reflect.get(value, 'sha');
  const description: unknown = Reflect.get(value, 'description') ?? '';
  if (typeof sha !== 'string' || !FULL_SHA_PATTERN.test(sha)) return undefined;
  if (typeof description !== 'string') return undefined;
  if (pr === undefined) return { sha, description };
  if (typeof pr !== 'number' || !Number.isInteger(pr) || pr <= 0) return undefined;
  return { pr, sha, description };
}

/**
 * Whether a target read from an artifact belongs to the run that is being reported. The artifact is
 * untrusted, so it must agree with what GitHub says about the triggering run: a push run checks
 * exactly its own commit and has no pull request; a pull request run checks its own head commit.
 */
export function isTargetForRun(target: CheckTarget, event: string, runHeadSha: string): boolean {
  if (event === 'push') return target.pr === undefined && target.sha === runHeadSha;
  if (event === 'pull_request') return target.pr !== undefined && target.sha === runHeadSha;
  return false;
}

/** A result is reported only while the checked commit is still the head. */
export function shouldReportResult(checkedSha: string, currentHeadSha: string): boolean {
  return checkedSha === currentHeadSha;
}

const MAX_STATUS_DESCRIPTION_LENGTH = 140;

export function buildStatus(
  conclusion: string,
  description: string,
  targetUrl: string,
): {
  state: 'success' | 'failure';
  context: string;
  description: string;
  target_url: string;
} {
  const state = conclusion === 'success' ? 'success' : 'failure';
  // A failed run still holding the placeholder ended before any step wrote a real description.
  const finalDescription =
    state === 'failure' && description === PLACEHOLDER_DESCRIPTION
      ? 'Check failed unexpectedly; see the run log'
      : description;
  return {
    state,
    context: STATUS_CONTEXT,
    description: finalDescription.slice(0, MAX_STATUS_DESCRIPTION_LENGTH),
    target_url: targetUrl,
  };
}

export function staleDistInstructions(changedFiles: readonly string[]): string {
  return [
    'The committed dist/ of the libraries is out of date. These files differ from a fresh build:',
    ...changedFiles.map((file) => `  ${file}`),
    '',
    'Merge the base branch into your branch, run `npm run build:pbu` and `npm run build:pbr`, commit the rebuilt dist/, and push.',
  ].join('\n');
}
